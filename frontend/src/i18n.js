export function errorMessage(t, code, cfg) {
  const m = t.errors[code] ?? t.errors.internal;
  if (typeof m !== 'function') return m;
  return code === 'too_long' ? m(cfg.max_duration_min) : m(cfg.max_upload_mb);
}
